import fs from 'fs';
import process from 'process';

// Path to the JSON file containing the map data
const mapDataPath = process.argv[2];
if (!mapDataPath) {
    throw new Error('No map data path provided. Usage: node convertMap.js <mapDataPath> <assetPath> <tilesetpxw> <tilesetpxh>');
}

// Retrieve command line arguments for asset path and dimensions
const assetPath = process.argv[3];
if (!assetPath) {
    throw new Error('No asset path provided. Usage: node convertMap.js <mapDataPath> <assetPath> <tilesetpxw> <tilesetpxh>');
}

const tilesetpxw = parseInt(process.argv[4], 10);
if (isNaN(tilesetpxw)) {
    throw new Error('Tileset pixel width must be a number. Usage: node convertMap.js <mapDataPath> <assetPath> <tilesetpxw> <tilesetpxh>');
}

const tilesetpxh = parseInt(process.argv[5], 10);
if (isNaN(tilesetpxh)) {
    throw new Error('Tileset pixel height must be a number. Usage: node convertMap.js <mapDataPath> <assetPath> <tilesetpxw> <tilesetpxh>');
}

// Name of the tile layer holding static collision, and of the object layer holding anchors.
// See docs/07-map-entity-split.md §4.4.
const COLLISION_LAYER = 'collision';
const ANCHOR_LAYER = 'anchors';

// Read the JSON file and parse it
const tiledMapData = JSON.parse(fs.readFileSync(mapDataPath, 'utf8'));

const tileDimension = tiledMapData.tilewidth;
const width = tiledMapData.width;
const height = tiledMapData.height;

// Function to convert Tiled 1D array to 3D array for the game engine
function convertLayerData(layerData, width, height) {
  let newArray = [];
  for (let i = 0; i < width; i++) {
    newArray[i] = [];
    for (let j = 0; j < height; j++) {
      newArray[i][j] = layerData[j * width + i] - 1;
    }
  }
  return [newArray];
}

// The collision layer is a bitmap, not tile indices: any painted tile is solid.
// `collision[x][y]`, same orientation as the tile layers.
function convertCollisionData(layerData, width, height) {
  let newArray = [];
  for (let i = 0; i < width; i++) {
    newArray[i] = [];
    for (let j = 0; j < height; j++) {
      newArray[i][j] = layerData[j * width + i] !== 0;
    }
  }
  return newArray;
}

function tiledProperty(object, name) {
  const property = (object.properties ?? []).find((p) => p.name === name);
  return property ? property.value : undefined;
}

// Tiled object layers are named rectangles in pixel space. Anchors are the same thing in
// tile space, plus the prose the writer agent reads.
function convertAnchors(layer) {
  const anchors = {};
  for (const object of layer.objects ?? []) {
    if (!object.name) {
      console.warn(`Skipping unnamed object in layer "${layer.name}" at (${object.x}, ${object.y}).`);
      continue;
    }
    if (anchors[object.name]) {
      throw new Error(`Duplicate anchor id "${object.name}" in layer "${layer.name}".`);
    }
    const description = tiledProperty(object, 'description');
    if (!description) {
      console.warn(`Anchor "${object.name}" has no "description" property; the writer agent will see it unlabelled.`);
    }
    anchors[object.name] = {
      x: Math.floor(object.x / tiledMapData.tilewidth),
      y: Math.floor(object.y / tiledMapData.tileheight),
      w: Math.max(1, Math.round((object.width ?? 0) / tiledMapData.tilewidth)),
      h: Math.max(1, Math.round((object.height ?? 0) / tiledMapData.tileheight)),
      description: description ?? '',
    };
  }
  return anchors;
}

// Process each layer and prepare JS module content
let jsContent = `// Map generated by convertMap.js\n\n`;
jsContent += `export const tilesetpath = "${assetPath}";\n`;
jsContent += `export const tiledim = ${tileDimension};\n`;
jsContent += `export const screenxtiles = ${width};\n`;
jsContent += `export const screenytiles = ${height};\n`;
jsContent += `export const tilesetpxw = ${tilesetpxw};\n`;
jsContent += `export const tilesetpxh = ${tilesetpxh};\n\n`;

let firstTileLayer = null;
let sawCollision = false;
let sawAnchors = false;

tiledMapData.layers.forEach(layer => {
  if (layer.type === 'objectgroup') {
    if (layer.name !== ANCHOR_LAYER) {
      console.warn(`Ignoring object layer "${layer.name}"; only "${ANCHOR_LAYER}" is converted.`);
      return;
    }
    jsContent += `export const anchors = ${JSON.stringify(convertAnchors(layer), null, 2)};\n`;
    sawAnchors = true;
    return;
  }
  if (layer.type !== 'tilelayer') {
    console.warn(`Ignoring layer "${layer.name}" of type "${layer.type}".`);
    return;
  }
  if (layer.name === COLLISION_LAYER) {
    const collision = convertCollisionData(layer.data, layer.width, layer.height);
    jsContent += `export const collision = ${JSON.stringify(collision)};\n`;
    sawCollision = true;
    return;
  }
  firstTileLayer = firstTileLayer ?? layer;
  const processedData = convertLayerData(layer.data, layer.width, layer.height);
  jsContent += `export const ${layer.name} = ${JSON.stringify(processedData)};\n`;
});

if (!sawAnchors) {
  console.warn(`No "${ANCHOR_LAYER}" object layer found; the world file will have nowhere to anchor entities.`);
  jsContent += `export const anchors = {};\n`;
}
if (!sawCollision) {
  // Omitted rather than empty: WorldMap derives collision from the object layers when the
  // field is absent, which is how unmigrated maps keep working. See docs/07 §5.1.
  console.warn(`No "${COLLISION_LAYER}" tile layer found; collision will be derived from the object layers at load.`);
}

// TODO: Add animated sprites
jsContent += `export const animatedsprites = [

]\n`

// Optionally, add map dimensions based on the first tile layer
if (firstTileLayer) {
  jsContent += `export const mapwidth = ${firstTileLayer.width};\n`;
  jsContent += `export const mapheight = ${firstTileLayer.height};\n`;
}

// Write the processed data to the final JS file
fs.writeFileSync('converted-map.js', jsContent);

console.log('Map conversion and JS module creation complete.');
